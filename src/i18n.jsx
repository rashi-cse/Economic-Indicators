function translate(value) {
  if (!value || typeof value !== 'string') return value;
  if (EXACT[value]) return EXACT[value];
  if (DATA_LABELS[value]) return DATA_LABELS[value];
  let out = value;
  for (const [from, to] of [...PHRASES, ...Object.entries(EXACT), ...Object.entries(DATA_LABELS)]
    .sort((a, b) => b[0].length - a[0].length)) {
    const escaped = from.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
    const pattern = /^[\w]+(?:[ -][\w]+)*$/u.test(from)
      ? new RegExp(`\\b${escaped}\\b`, 'gu')
      : new RegExp(escaped, 'gu');
    out = out.replace(pattern, to);
  }
  return out;
}

function useTranslatedDom(language) {
  const originals = useRef(new WeakMap());
  const attributes = useRef(new WeakMap());

  useEffect(() => {
    document.documentElement.lang = language === 'hi' ? 'hi' : 'en';
    const root = document.body;
    let updating = false;
    const update = () => {
      if (updating) return;
      updating = true;
      const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
      let node;
      while ((node = walker.nextNode())) {
        const saved = originals.current.get(node);
        if (language === 'hi') {
          // React-owned text may change after the observer runs (for example
          // animated figures). Never preserve the initial loading placeholder
          // as the source text for a later render.
          const original = saved && node.nodeValue === translate(saved) ? saved : node.nodeValue;
          originals.current.set(node, original);
          const next = translate(original);
          if (node.nodeValue !== next) node.nodeValue = next;
        } else if (saved && node.nodeValue === translate(saved) && node.nodeValue !== saved) {
          // Restore only text translated by this observer. Fresh English text
          // rendered by React must be left untouched.
          node.nodeValue = saved;
        }
      }
      root.querySelectorAll('[aria-label],[title],[placeholder]').forEach((el) => {
        let saved = attributes.current.get(el);
        if (!saved) {
          saved = {};
          attributes.current.set(el, saved);
        }
        ['aria-label', 'title', 'placeholder'].forEach((name) => {
          if (el.hasAttribute(name) && saved[name] == null) saved[name] = el.getAttribute(name);
          if (saved[name] != null) {
            const next = language === 'hi' ? translate(saved[name]) : saved[name];
            if (el.getAttribute(name) !== next) el.setAttribute(name, next);
          }
        });
      });
      updating = false;
    };
    update();
    const observer = new MutationObserver(update);
    observer.observe(root, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ['aria-label', 'title', 'placeholder'] });
    return () => observer.disconnect();
  }, [language, originals, attributes]);
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(() => {
    try { return localStorage.getItem('site-language') === 'hi' ? 'hi' : 'en'; } catch { return 'en'; }
  });
  const changeLanguage = (next) => {
    setLanguage(next);
    try { localStorage.setItem('site-language', next); } catch { /* keep it for this visit */ }
  };
  useTranslatedDom(language);
  const value = useMemo(() => ({ language, setLanguage: changeLanguage }), [language]);
  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const value = useContext(LanguageContext);
  if (!value) throw new Error('useLanguage must be used inside LanguageProvider');
  return value;
}

export function LanguageToggle() {
  const { language, setLanguage } = useLanguage();
  const hindi = language === 'hi';
  return (
    <div className="eb-language-switch" role="group" aria-label={hindi ? 'भाषा' : 'Language'}>
      <button type="button" aria-pressed={!hindi} onClick={() => setLanguage('en')}>{hindi ? 'अ' : 'A'} <span>{hindi ? 'अंग्रेज़ी' : 'English'}</span></button>
      <button type="button" aria-pressed={hindi} onClick={() => setLanguage('hi')}>अ <span>हिंदी</span></button>
    </div>
  );
}
